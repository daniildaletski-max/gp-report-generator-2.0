function useCountUp(target: number, durationMs = 900): number {
  const [val, setVal] = useState(0);
  useEffect(() => {
    let frame: number;
    const start = performance.now();
    const tick = (t: number) => {
      const k = Math.min(1, (t - start) / durationMs);
      const eased = 1 - Math.pow(1 - k, 3); // ease-out cubic
      setVal(target * eased);
      if (k < 1) frame = requestAnimationFrame(tick);
    };
    frame = requestAnimationFrame(tick);
    return () => cancelAnimationFrame(frame);
  }, [target, durationMs]);
  return val;
}

/**
 * Tiny dependency-free sparkline. Hand-rolled SVG (not recharts) so it
 * renders crisply in the constrained hero slot without a ResponsiveContainer
 * fighting for height. Draws a soft area fill + line + an endpoint dot.
 */
function Sparkline({
  values, color = "#f59e0b", width = 132, height = 44,
}: { values: number[]; color?: string; width?: number; height?: number }) {
  const clean = (values ?? []).filter((v) => Number.isFinite(v));
  if (clean.length < 2) return null;
  const min = Math.min(...clean);
  const max = Math.max(...clean);
  const range = max - min || 1;
  const pad = 4;
  const pts = clean.map((v, i) => {
    const x = pad + (i / (clean.length - 1)) * (width - pad * 2);
    const y = pad + (1 - (v - min) / range) * (height - pad * 2);
    return [x, y] as const;
  });
  const line = pts.map(([x, y], i) => `${i === 0 ? "M" : "L"}${x.toFixed(1)},${y.toFixed(1)}`).join(" ");
  const area = `${line} L${pts[pts.length - 1][0].toFixed(1)},${(height - pad).toFixed(1)} L${pts[0][0].toFixed(1)},${(height - pad).toFixed(1)} Z`;
  const [lx, ly] = pts[pts.length - 1];
  const gradId = `gp-spark-${color.replace("#", "")}`;
  return (
    <svg width={width} height={height} viewBox={`0 0 ${width} ${height}`} aria-hidden className="overflow-visible">
      <defs>
        <linearGradient id={gradId} x1="0" y1="0" x2="0" y2="1">
          <stop offset="0%" stopColor={color} stopOpacity={0.22} />
          <stop offset="100%" stopColor={color} stopOpacity={0} />
        </linearGradient>
      </defs>
      <path d={area} fill={`url(#${gradId})`} />
      <path d={line} fill="none" stroke={color} strokeWidth={2} strokeLinecap="round" strokeLinejoin="round" />
      <circle cx={lx} cy={ly} r={3} fill={color} />
      <circle cx={lx} cy={ly} r={6} fill={color} opacity={0.18} />
    </svg>
  );
}

export function PerformancePulseHero({
  gpFirstName,
  greeting,
  avgScore,
  maxScore,
  avgAppearance,
  maxAppearance,
  avgGamePerf,
  maxGamePerf,
  evaluationsCount,
  tierName,
  tierAccent,
  TierIcon,
  delta,
  deltaLabel,
  cleanStreak,
  lastEvaluationDate,
  nextTier,
  availableMonths,
  selectedMonth,
  selectedYear,
  onMonthChange,
  isLoadingMonth,
  trend,
}: {
  gpFirstName: string;
  greeting: string;
  avgScore: number;
  maxScore: number;
  /** Optional sub-scores. When provided, the hero renders three
   *  Apple-Watch-style concentric rings (Overall · Appearance · Game)
   *  instead of a single pulse ring. */
  avgAppearance?: number;
  maxAppearance?: number;
  avgGamePerf?: number;
  maxGamePerf?: number;
  evaluationsCount: number;
  tierName: string;
  tierAccent: string;
  TierIcon: typeof Star;
  delta: number | null;
  deltaLabel: string | null;
  cleanStreak: number;
  lastEvaluationDate: Date | null;
  /** Optional tier-progress hint, e.g. { nextName: "Pro", pointsAway: 1.4 }.
   *  When set, surfaces "1.4 pts → Pro" so the GP has a concrete next
   *  goal anchored to the same tier vocabulary as the badge inside the
   *  ring. Pass `null` when already top-tier. */
  nextTier?: { nextName: string; pointsAway: number } | null;
  /** Month selector — when provided, renders a compact month picker
   *  inline with the hero so GPs can switch months without scrolling. */
  availableMonths?: Array<{ month: number; year: number; label: string; evalCount: number; hasData?: boolean }>;
  selectedMonth?: number;
  selectedYear?: number;
  onMonthChange?: (month: number, year: number) => void;
  isLoadingMonth?: boolean;
  /** Recent monthly average totals (oldest→newest) for the hero sparkline. */
  trend?: number[];
}) {
  const animated = useCountUp(avgScore, 900);
  const overallPct = maxScore > 0 ? Math.min(100, Math.max(0, (avgScore / maxScore) * 100)) : 0;

  // Animate bars from 0% → target on mount / data change
  const [barMounted, setBarMounted] = useState(false);
  useEffect(() => {
    const id = requestAnimationFrame(() => setBarMounted(true));
    return () => { cancelAnimationFrame(id); setBarMounted(false); };
  }, [avgScore, avgAppearance, avgGamePerf]);
  const appearancePct = (avgAppearance != null && maxAppearance && maxAppearance > 0)
    ? Math.min(100, Math.max(0, (avgAppearance / maxAppearance) * 100))
    : null;
  const gamePerfPct = (avgGamePerf != null && maxGamePerf && maxGamePerf > 0)
    ? Math.min(100, Math.max(0, (avgGamePerf / maxGamePerf) * 100))
    : null;
  const showSubScores = appearancePct != null && gamePerfPct != null;

  return (
    <section className="relative overflow-hidden rounded-[28px] border border-slate-200/70 bg-white shadow-[0_1px_3px_rgba(0,0,0,0.03)]">
      <div className="relative p-8 sm:p-12">
        {/* Header row — greeting + tier chip pinned right. Reads as
            metadata above the headline, not a decorated banner. */}
        <div className="flex items-start justify-between gap-3 mb-5">
          <p className="text-[11px] text-slate-500 uppercase tracking-[0.2em] font-semibold">{greeting}</p>
          <span className={`inline-flex items-center gap-1 px-2.5 py-1 rounded-full text-[10px] font-semibold uppercase tracking-widest bg-gradient-to-br ${tierAccent} text-white shrink-0`}>
            <TierIcon className="h-3 w-3" />
            {tierName}
          </span>
        </div>

        {/* Name */}
        <h1 className="text-[28px] sm:text-4xl font-semibold text-slate-900 leading-[1.05] tracking-tight">
          {gpFirstName}'s pulse
        </h1>
        <p className="text-sm text-slate-400 mt-2.5">
          {evaluationsCount} evaluation{evaluationsCount !== 1 ? "s" : ""}{selectedMonth ? ` this month` : ` on record`} · keep stacking the wins
        </p>

        {/* Primary metric — score, max, delta, all in one elegant
            line. The big number anchors the hero without a giant
            ring stealing real estate. Wrapped in a transition container
            that fades/slides when the month changes. */}
        <div
          key={`${selectedMonth}-${selectedYear}`}
          className={`mt-7 flex flex-col sm:flex-row sm:items-end gap-x-6 gap-y-3 sm:flex-wrap animate-in fade-in-0 slide-in-from-bottom-2 duration-300 ${isLoadingMonth ? 'opacity-50 transition-opacity' : ''}`}>
          <div className="flex items-baseline gap-2">
            <span className="text-7xl sm:text-8xl font-semibold text-slate-900 tabular-nums leading-none tracking-tighter">
              {animated.toFixed(1)}
            </span>
            <span className="text-3xl text-slate-300 font-light leading-none">/{maxScore}</span>
          </div>
          <div className="flex items-center gap-2 flex-wrap pb-1">
            {delta !== null && (
              <span className={`inline-flex items-center gap-1 text-xs font-medium px-2 py-0.5 rounded-full border ${
                delta >= 0
                  ? "border-emerald-200 bg-emerald-50/70 text-emerald-700"
                  : "border-rose-200 bg-rose-50/70 text-rose-700"
              }`}>
                {delta >= 0 ? <TrendingUp className="h-3 w-3" /> : <TrendingDown className="h-3 w-3" />}
                {delta >= 0 ? "+" : ""}{delta.toFixed(1)} {deltaLabel ? `vs ${deltaLabel}` : ""}
              </span>
            )}
            {nextTier && (
              <span className="inline-flex items-center gap-1 text-xs font-medium px-2 py-0.5 rounded-full border border-amber-200 bg-amber-50/70 text-amber-700">
                <Target className="h-3 w-3" />
                {nextTier.pointsAway.toFixed(1)} to {nextTier.nextName}
              </span>
            )}
            {cleanStreak >= 2 && (
              <span className="inline-flex items-center gap-1 text-xs font-medium px-2 py-0.5 rounded-full border border-amber-200 bg-amber-50/70 text-amber-700">
                {cleanStreak >= 5 ? <Crown className="h-3 w-3" /> : <Flame className="h-3 w-3" />}
                {cleanStreak} clean in a row
              </span>
            )}
          </div>

          {/* Trajectory sparkline — turns the "+x vs last month" chip into a
              visible story of where the GP is heading. */}
          {trend && trend.length >= 2 && (
            <div className="sm:ml-auto flex flex-col items-end gap-1 pb-1">
              <Sparkline values={trend} color="#f59e0b" />
              <span className="text-[10px] uppercase tracking-[0.14em] text-slate-400 font-semibold">
                last {trend.length} months
              </span>
            </div>
          )}
        </div>

        {/* Primary progress bar — horizontal, takes the full width.
            Replaces the ring as the visual reference for "where am I". */}
        <div className="mt-5">
          <div className="h-2 bg-slate-100 rounded-full overflow-hidden">
            <div
              className="h-full rounded-full bg-gradient-to-r from-amber-400 to-orange-500 transition-[width] duration-1000 ease-out"
              style={{ width: barMounted ? `${overallPct}%` : '0%' }}
            />
          </div>
          <div className="mt-1.5 flex items-center justify-between text-[11px] text-slate-400 font-medium tabular-nums">
            <span>{overallPct.toFixed(0)}% of max</span>
            {lastEvaluationDate && (
              <span className="inline-flex items-center gap-1 text-slate-500">
                <Zap className="h-3 w-3 text-amber-500" />
                Last eval {formatDistanceToNow(lastEvaluationDate, { addSuffix: true })}
              </span>
            )}
          </div>
        </div>

        {/* Month selector — compact inline picker so GPs can switch
            the viewed month directly from the hero card. */}
        {availableMonths && availableMonths.length > 0 && onMonthChange && (
          <div className="mt-5 flex items-center gap-2 flex-wrap">
            <span className="text-[11px] uppercase tracking-[0.14em] text-slate-400 font-semibold mr-1">Month</span>
            {availableMonths.map(m => {
              const isActive = m.month === selectedMonth && m.year === selectedYear;
              return (
                <button
                  key={`${m.year}-${m.month}`}
                  onClick={() => onMonthChange(m.month, m.year)}
                  disabled={!(m.hasData ?? m.evalCount > 0)}
                  className={`px-2.5 py-1 rounded-lg text-[11px] font-semibold transition-all duration-200 border ${
                    isActive
                      ? 'bg-slate-900 text-white border-slate-900 shadow-sm'
                      : (m.hasData ?? m.evalCount > 0)
                        ? 'bg-white border-slate-200 text-slate-500 hover:border-slate-300 hover:bg-slate-50'
                        : 'bg-slate-50 border-slate-100 text-slate-300 cursor-not-allowed'
                  }`}
                >
                  {m.label}
                </button>
              );
            })}
          </div>
        )}

        {/* Sub-scores — two clean rows, each with label + value + slim
            colored bar. No more concentric ring soup. */}
        {showSubScores && (
          <div key={`sub-${selectedMonth}-${selectedYear}`} className={`mt-7 pt-5 border-t border-slate-100 grid grid-cols-1 sm:grid-cols-2 gap-x-8 gap-y-4 animate-in fade-in-0 slide-in-from-bottom-1 duration-500 ${isLoadingMonth ? 'opacity-50' : ''}`}>
            {[
              { key: "appearance", label: "Appearance", value: avgAppearance!, max: maxAppearance!, pct: appearancePct!, color: "#0f172a", bg: "bg-slate-800" },
              { key: "game", label: "Game performance", value: avgGamePerf!, max: maxGamePerf!, pct: gamePerfPct!, color: "#94a3b8", bg: "bg-slate-400" },
            ].map(s => (
              <div key={s.key}>
                <div className="flex items-baseline justify-between gap-2">
                  <span className="inline-flex items-center gap-2 text-[11px] uppercase tracking-[0.14em] text-slate-500 font-semibold">
                    <span className="h-1.5 w-1.5 rounded-full" style={{ backgroundColor: s.color }} aria-hidden />
                    {s.label}
                  </span>
                  <span className="text-sm font-semibold text-slate-800 tabular-nums">
                    {s.value.toFixed(1)}<span className="text-slate-400 font-normal"> / {s.max}</span>
                  </span>
                </div>
                <div className="mt-2 h-1 bg-slate-100 rounded-full overflow-hidden">
                  <div
                    className={`h-full rounded-full ${s.bg} transition-[width] duration-1000 ease-out`}
                    style={{
                      width: barMounted ? `${s.pct}%` : '0%',
                      transitionDelay: s.key === 'appearance' ? '200ms' : '400ms',
                    }}
                  />
                </div>
              </div>
            ))}
          </div>
        )}
      </div>
    </section>
  );
}

