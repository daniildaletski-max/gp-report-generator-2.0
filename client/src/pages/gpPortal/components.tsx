// ============================================================================
// At-a-glance strip — 4 micro-stats below the hero
// ============================================================================

export function AtAGlanceStrip({
  evalCount, mistakes, attitude, lastEvaluationDate, trends,
}: {
  evalCount: number;
  mistakes: number;
  attitude: number;
  lastEvaluationDate: Date | null;
  /** Per-month series (oldest→newest) powering the mini-sparklines. */
  trends?: { evals?: number[]; mistakes?: number[]; attitude?: number[] };
}) {
  const recencyLabel = lastEvaluationDate
    ? formatDistanceToNow(lastEvaluationDate, { addSuffix: true })
    : "—";
  // Single neutral tile — distinguishes itself by the icon tint
  // alone, not the whole tile background. Reads as a clean
  // "card row" instead of four competing colour blocks. A small
  // sparkline on the right turns each number into a trend.
  const spark = (s: number[] | undefined) =>
    s && s.filter(Number.isFinite).length >= 2 ? { values: s } : undefined;
  const tiles: Array<{ icon: typeof Eye; label: string; value: string | number; spark?: { values: number[] } }> = [
    { icon: Eye, label: "Evaluations", value: evalCount, spark: spark(trends?.evals) },
    { icon: AlertTriangle, label: "Mistakes", value: mistakes, spark: spark(trends?.mistakes) },
    { icon: ThumbsUp, label: "Attitude", value: attitude > 0 ? `+${attitude}` : `${attitude}`, spark: spark(trends?.attitude) },
    { icon: Clock, label: "Last eval", value: recencyLabel },
  ];
  return (
    <div className="grid grid-cols-2 sm:grid-cols-4 gap-4">
      {tiles.map(t => (
        <div
          key={t.label}
          className="rounded-2xl border border-slate-200/70 bg-white p-4 sm:p-5 flex items-center gap-3.5"
        >
          <t.icon className="h-4 w-4 text-slate-300 shrink-0" aria-hidden />
          <div className="min-w-0 flex-1">
            <p className="text-[10px] uppercase tracking-[0.16em] text-slate-400 font-semibold">{t.label}</p>
            <p className="text-xl sm:text-2xl font-semibold text-slate-900 truncate leading-tight tabular-nums mt-0.5">{t.value}</p>
          </div>
          {t.spark && (
            <div className="shrink-0 hidden sm:block self-center">
              <Sparkline values={t.spark.values} color="#cbd5e1" width={52} height={24} />
            </div>
          )}
        </div>
      ))}
    </div>
  );
}

