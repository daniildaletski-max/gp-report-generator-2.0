// Score card — large metric display with premium hover effects
// ============================================================================

export function ScoreCard({ score, maxScore, label, icon: Icon, accentColor, bgColor, tooltip, delta, trend, sparkColor }: {
  score: number; maxScore: number; label: string; icon: typeof Star; accentColor: string; bgColor: string; tooltip?: string;
  delta?: number | null;
  trend?: Array<{ value: number }>;
  sparkColor?: string;
}) {
  const percentage = maxScore > 0 ? (score / maxScore) * 100 : 0;
  const [showTooltip, setShowTooltip] = useState(false);

  const getStatus = () => {
    if (percentage >= 90) return { text: 'Excellent', color: 'text-emerald-600', badge: 'bg-emerald-50 border-emerald-200 text-emerald-700' };
    if (percentage >= 80) return { text: 'Great', color: 'text-green-600', badge: 'bg-green-50 border-green-200 text-green-700' };
    if (percentage >= 70) return { text: 'Good', color: 'text-amber-600', badge: 'bg-amber-50 border-amber-200 text-amber-700' };
    return { text: 'Needs Work', color: 'text-red-600', badge: 'bg-red-50 border-red-200 text-red-700' };
  };
  const status = getStatus();
  const showDelta = typeof delta === "number" && delta !== 0;

  return (
    <div className="relative overflow-hidden rounded-2xl bg-white p-6 border border-slate-200/70 shadow-[0_1px_3px_rgba(0,0,0,0.03)] transition-shadow duration-300">
      <div className="relative z-10">
        <div className="flex items-center justify-between mb-5">
          <div className="p-2 rounded-xl border bg-slate-50 border-slate-200">
            <Icon className="h-4 w-4 text-slate-400" />
          </div>
          <div className="flex items-center gap-2">
            {tooltip && (
              <div className="relative">
                <button
                  onClick={() => setShowTooltip(!showTooltip)}
                  className="p-1 rounded-full hover:bg-slate-100 transition-colors"
                  aria-label="Score formula"
                >
                  <Info className="h-3.5 w-3.5 text-slate-400" />
                </button>
                {showTooltip && (
                  <div className="absolute right-0 top-7 z-50 w-48 p-3 bg-white border border-slate-200 rounded-xl text-xs text-slate-600 shadow-md">
                    {tooltip}
                  </div>
                )}
              </div>
            )}
            <span className="text-[10px] uppercase tracking-[0.14em] font-semibold text-slate-400">{status.text}</span>
          </div>
        </div>
        <div className="mb-3">
          <p className="text-[11px] uppercase tracking-[0.16em] text-slate-500 font-semibold">{label}</p>
          <div className="flex items-baseline gap-1.5 flex-wrap mt-1">
            <span className="text-4xl sm:text-[44px] font-semibold text-slate-900 tabular-nums leading-none tracking-tight">{score.toFixed(1)}</span>
            <span className="text-lg text-slate-300 font-light">/{maxScore}</span>
            {showDelta && (
              <span className={`ml-1 inline-flex items-center gap-0.5 text-[11px] font-semibold ${
                (delta as number) > 0
                  ? "text-emerald-600"
                  : "text-rose-500"
              }`}>
                {(delta as number) > 0 ? <TrendingUp className="h-3 w-3" /> : <TrendingDown className="h-3 w-3" />}
                {(delta as number) > 0 ? "+" : ""}{(delta as number).toFixed(1)}
              </span>
            )}
          </div>
        </div>
        {/* Slim progress bar — single accent colour, no gradient
            soup. Width animates on first paint. */}
        <div className="h-1.5 bg-slate-100 rounded-full overflow-hidden">
          <div
            className="h-full rounded-full transition-[width] duration-1000 ease-out"
            style={{ width: `${percentage}%`, backgroundColor: sparkColor || "#f59e0b" }}
          />
        </div>
        {trend && trend.length >= 2 && (() => {
          // SVG `id` attributes can't contain whitespace — when the
          // label has a space ("Overall Score", "Game Performance")
          // the `url(#spark-Overall Score)` reference becomes invalid
          // and the fill silently falls back to the default black
          // colour, producing the dirty grey smudge under the line.
          // Slugify the label so the gradient resolves cleanly.
          const slug = label.replace(/\s+/g, "-").toLowerCase();
          return (
            <div className="mt-3 h-10 -mx-1" aria-hidden>
              <ResponsiveContainer width="100%" height="100%">
                <AreaChart data={trend} margin={{ top: 2, right: 2, left: 2, bottom: 0 }}>
                  <defs>
                    <linearGradient id={`spark-${slug}`} x1="0" y1="0" x2="0" y2="1">
                      <stop offset="0%" stopColor={sparkColor || "#f59e0b"} stopOpacity={0.35} />
                      <stop offset="100%" stopColor={sparkColor || "#f59e0b"} stopOpacity={0} />
                    </linearGradient>
                  </defs>
                  <Area
                    type="monotone"
                    dataKey="value"
                    stroke={sparkColor || "#f59e0b"}
                    strokeWidth={2}
                    fill={`url(#spark-${slug})`}
                    isAnimationActive={false}
                    dot={false}
                  />
                </AreaChart>
              </ResponsiveContainer>
            </div>
          );
        })()}
      </div>
    </div>
  );
}

