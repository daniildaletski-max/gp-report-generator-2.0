export function AchievementBadge({ icon: Icon, title, description, unlocked, color, progress, progressLabel, rarity }: {
  icon: typeof Star;
  title: string;
  description: string;
  unlocked: boolean;
  color: string;
  /** 0–1 progress to unlock. When set on a locked badge, a progress bar
   *  + percentage replace the dim grayscale state — turns "locked"
   *  badges into a visible goal instead of dead space. */
  progress?: number | null;
  /** Short progress hint, e.g. "3/5 evaluations" or "+1.2 to go". */
  progressLabel?: string | null;
  /** Visual hierarchy on the badge — common feels earned, legendary
   *  feels like a flex. Drives the rim/glow treatment when unlocked. */
  rarity?: "common" | "rare" | "epic" | "legendary";
}) {
  const showProgress = !unlocked && typeof progress === "number" && progress > 0;
  const almostThere = showProgress && (progress as number) >= 0.66;
  // Editorial badges: every tile is a quiet white card; rarity reads as a
  // small uppercase word, unlocked as an amber tick + amber rarity text.
  // The old per-achievement tile colours are intentionally ignored.
  void color;
  const rarityText =
    !rarity ? null :
    rarity === "legendary" ? "Legendary" :
    rarity === "epic" ? "Epic" :
    rarity === "rare" ? "Rare" : "Common";
  return (
    <div className={`relative p-4 rounded-2xl border bg-white transition-colors duration-200 group cursor-default ${
      unlocked
        ? "border-amber-300"
        : showProgress
          ? `border-slate-200/70 hover:border-slate-300 ${almostThere ? "border-amber-200" : ""}`
          : "border-slate-200/70 opacity-55"
    }`}>
      <div className="flex items-center gap-3 relative">
        <div className={`shrink-0 h-10 w-10 rounded-full border flex items-center justify-center ${
          unlocked ? "bg-[#FAF9F7] border-amber-200" : "bg-[#FAF9F7] border-slate-200"
        }`}>
          <Icon className={`h-4.5 w-4.5 ${unlocked ? "text-amber-600" : "text-slate-300"}`} />
        </div>
        <div className="min-w-0 flex-1">
          <div className="flex items-center gap-1.5 flex-wrap">
            <p className={`font-semibold text-sm truncate ${unlocked || showProgress ? "text-slate-900" : "text-slate-400"}`}>{title}</p>
            {rarityText && (
              <span className={`shrink-0 text-[9px] uppercase tracking-[0.14em] font-semibold ${
                unlocked ? "text-amber-600" : "text-slate-300"
              }`}>
                {rarityText}
              </span>
            )}
          </div>
          <p className={`text-xs truncate ${unlocked || showProgress ? "text-slate-400" : "text-slate-300"}`}>{description}</p>
          {showProgress && (
            <div className="mt-2 flex items-center gap-2">
              <div className="flex-1 h-1 rounded-full bg-slate-100 overflow-hidden">
                <div
                  className={`h-full rounded-full transition-[width] duration-700 ease-out ${almostThere ? "bg-amber-500" : "bg-slate-300"}`}
                  style={{ width: `${Math.min(100, Math.max(4, (progress as number) * 100))}%` }}
                />
              </div>
              <span className={`text-[10px] font-medium tabular-nums shrink-0 ${almostThere ? "text-amber-600" : "text-slate-400"}`}>
                {progressLabel ?? `${Math.round((progress as number) * 100)}%`}
              </span>
            </div>
          )}
        </div>
        {unlocked && (
          <span className="shrink-0 text-amber-500 text-sm font-semibold" aria-label="Unlocked">✓</span>
        )}
      </div>
    </div>
  );
}

// ============================================================================
// Stat card — compact metric tile with gold hover
// ============================================================================

export function StatCard({ icon: Icon, value, label, color, trend, hint, trendIsPositiveWhenDown }: {
  icon: typeof Eye;
  value: string | number;
  label: string;
  color: string;
  trend?: number;
  /** Short sub-line ("vs last month", "of 13 in team"). Replaces the
   *  empty caption space below the label so zero-stat cards aren't
   *  visually dead. */
  hint?: string | null;
  /** When true (e.g. for "Mistakes") a NEGATIVE trend is good and
   *  should render in green. Defaults to "up = good = green" semantics. */
  trendIsPositiveWhenDown?: boolean;
}) {
  // Decide trend tone from `trendIsPositiveWhenDown` so each card can
  // express its own "lower is better" vs "higher is better" intent.
  const trendIsGood =
    trend !== undefined && trend !== 0 && (trendIsPositiveWhenDown ? trend < 0 : trend > 0);
  void color; // tile colour intentionally dropped for the editorial look
  return (
    <div className="relative bg-white rounded-2xl border border-slate-200/70 overflow-hidden transition-shadow duration-300">
      <div className="p-5 sm:p-6 relative">
        <div className="flex items-center gap-3.5 relative">
          <div className="bg-slate-50 p-2.5 rounded-xl shrink-0 border border-slate-200">
            <Icon className="h-5 w-5 text-slate-400" />
          </div>
          <div className="min-w-0 flex-1">
            <div className="flex items-center gap-2 flex-wrap">
              <p className="text-2xl sm:text-3xl font-semibold text-slate-900 leading-none tabular-nums">{value}</p>
              {trend !== undefined && trend !== 0 && (
                <span className={`inline-flex items-center gap-0.5 text-[11px] font-semibold ${
                  trendIsGood ? 'text-emerald-600' : 'text-rose-500'
                }`}>
                  {trend > 0 ? <TrendingUp className="h-3 w-3" /> : <TrendingDown className="h-3 w-3" />}
                  {trend > 0 ? '+' : ''}{trend.toFixed(1)}
                </span>
              )}
            </div>
            <p className="text-xs sm:text-sm text-slate-400 truncate mt-1">{label}</p>
            {hint && (
              <p className="text-[11px] text-slate-400 truncate mt-0.5">{hint}</p>
            )}
          </div>
        </div>
      </div>
    </div>
  );
}

